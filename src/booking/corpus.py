"""Hotel descriptions and reviews for the search knowledge base, deterministic for a seed.

Text is assembled from templates, not generated by a model, so a seed always yields the same corpus.
Each document has a Bedrock metadata sidecar; the search reads `hotel_id` back from it.
"""

import json
import random
from pathlib import Path

from booking.generator import SCALES, reference

STYLES = ("boutique", "business", "family", "design", "budget", "luxury")
AMENITIES = (
    "an outdoor pool",
    "a spa with a sauna",
    "a 24-hour gym",
    "a rooftop bar",
    "free breakfast",
    "free parking",
    "a pet-friendly policy",
    "a business centre",
    "family rooms with bunk beds",
    "bikes to borrow",
    "a quiet library lounge",
    "late checkout on request",
)
SETTINGS = {
    "New York": ("steps from Central Park", "in the heart of Midtown", "near the Brooklyn Bridge"),
    "Chicago": ("on the Magnificent Mile", "by the Riverwalk", "close to Millennium Park"),
    "London": ("near Covent Garden", "on the South Bank", "a short walk from Hyde Park"),
    "Berlin": ("in Mitte", "by the Spree in Kreuzberg", "near the Brandenburg Gate"),
    "Paris": ("in the Marais", "on the Left Bank", "a short walk from the Louvre"),
    "Tokyo": ("in Shinjuku", "near Tokyo Station", "by the gardens of Ueno"),
}
PRAISE = (
    "The staff were friendly and helpful.",
    "The bed was very comfortable and the room was quiet.",
    "Breakfast had plenty of choice.",
    "The location made it easy to explore on foot.",
    "Check-in was quick even late at night.",
    "Great value for the price.",
)
COMPLAINTS = (
    "The room was smaller than in the photos.",
    "Street noise kept us awake.",
    "The Wi-Fi was slow in the evenings.",
    "The lifts were often busy.",
)
REVIEWS_PER_HOTEL = 4


def document(seed: int, hotel: dict) -> tuple[str, dict]:
    """One hotel's text and its metadata sidecar."""
    rng = random.Random(f"{seed}:{hotel['hotel_id']}")
    style = rng.choice(STYLES)
    amenities = rng.sample(AMENITIES, 3)
    setting = rng.choice(SETTINGS[hotel["city"]])
    lines = [
        f"# {hotel['name']}",
        "",
        f"A {style} hotel in {hotel['city']}, {setting}. "
        f"Guests enjoy {amenities[0]}, {amenities[1]} and {amenities[2]}.",
        "",
        "## Reviews",
    ]
    for _ in range(REVIEWS_PER_HOTEL):
        rating = rng.choices((5, 4, 3, 2), weights=(4, 4, 2, 1))[0]
        remarks = rng.sample(PRAISE, 2) if rating >= 4 else [rng.choice(PRAISE)]
        if rating <= 3:
            remarks.append(rng.choice(COMPLAINTS))
        lines.append(f"- {rating}/5. " + " ".join(remarks))
    metadata = {
        "metadataAttributes": {
            "hotel_id": hotel["hotel_id"],
            "city": hotel["city"],
            "country": hotel["country"],
        }
    }
    return "\n".join(lines) + "\n", metadata


def write(out: Path, seed: int, scale_name: str) -> None:
    """`hotels/<hotel_id>.md` with `<hotel_id>.md.metadata.json` beside it, the layout a Bedrock
    S3 data source reads. The hotels are the generator's for the same seed and scale."""
    hotels = reference(seed, SCALES[scale_name])["hotels"]
    folder = out / "hotels"
    folder.mkdir(parents=True, exist_ok=True)
    for hotel in hotels:
        text, metadata = document(seed, hotel)
        path = folder / f"{hotel['hotel_id']}.md"
        path.write_text(text, encoding="utf-8")
        Path(f"{path}.metadata.json").write_text(json.dumps(metadata), encoding="utf-8")
